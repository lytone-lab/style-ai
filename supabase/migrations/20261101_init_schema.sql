begin;

create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);

alter table public.waitlist
  alter column email set not null,
  alter column created_at set default now(),
  alter column created_at set not null;

alter table public.waitlist
  drop constraint if exists waitlist_email_check;

alter table public.waitlist
  drop constraint if exists waitlist_email_length_check;

alter table public.waitlist
  add constraint waitlist_email_length_check
  check (char_length(email) <= 254);

alter table public.waitlist enable row level security;

do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'waitlist'
  loop
    execute format(
      'drop policy %I on public.waitlist',
      existing_policy.policyname
    );
  end loop;
end
$$;

revoke all on table public.waitlist from anon, authenticated;
grant insert on table public.waitlist to anon;

create policy "Allow public waitlist signups"
on public.waitlist
for insert
to anon
with check (char_length(email) <= 254);

commit;
